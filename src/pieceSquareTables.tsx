export function getPSTValue(type: string, color: string, row: number, col: number): number {

  if(type === 'k'){
    return 0;
  }
  const table = pstTables[type];
  const adjustedRow = color === 'w' ? row : 7 - row;
  return table[adjustedRow][col];
}

export function getKingPST(color: string, row: number, col: number, isEndGame: boolean): number{

  const adjustedRow = color === 'w' ? row : 7 - row;

  const table = isEndGame ? pstKingEndgame : pstKingMiddle

  return table[adjustedRow][col];
}