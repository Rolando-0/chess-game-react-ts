export function getPSTValue(type: string, color: string, row: number, col: number) {

  if(type === 'k'){
    return 0;
  }
  const table = pstTables[type];
  const adjustedRow = color === 'w' ? 7 - row : row;
  return table[adjustedRow][col];
}